// Regenerates src/testing/role-permissions.ts (the built-in roles' permission maps used by the
// authorization specs) from the backend's compiled role definitions. Both repos must sit side by
// side in the workspace, and the backend must be built first:
//   (cd ../Backend && npm run build) && node scripts/generate-role-fixtures.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../Backend/dist/src/modules/rbac/constants/role-definitions.js');
if (!fs.existsSync(source)) {
  console.error(`Missing ${source}. Build the backend first (cd ../Backend && npm run build).`);
  process.exit(1);
}
const { ROLE_DEFINITIONS } = await import(pathToFileURL(source).href);

const RANK = { own: 1, team: 2, all: 3 };
const roles = ROLE_DEFINITIONS.filter((role) => role.isActive !== false);

const lines = [
  '/**',
  ' * Permission maps of the built-in roles, mirroring the backend seed',
  ' * (Backend/src/modules/rbac/constants/role-definitions.ts). Generated by',
  ' * scripts/generate-role-fixtures.mjs — regenerate when the role definitions change.',
  ' * Used by the authorization specs to render the UI as each role.',
  ' */',
  "import type { PermissionCode } from '../app/core/auth/permission-code';",
  "import type { Scope } from '../app/core/auth/scope';",
  '',
  'export type RoleKey =',
  ...roles.map((role, index) => `  | '${role.code}'${index === roles.length - 1 ? ';' : ''}`),
  '',
  'export const ROLE_PERMISSIONS: Record<RoleKey, Partial<Record<PermissionCode, Scope>>> = {',
];
for (const role of roles) {
  const widest = new Map();
  for (const [code, scope] of role.grants) {
    if (!widest.has(code) || RANK[scope] > RANK[widest.get(code)]) widest.set(code, scope);
  }
  lines.push(`  ${role.code}: {`);
  for (const code of [...widest.keys()].sort()) lines.push(`    '${code}': '${widest.get(code)}',`);
  lines.push('  },');
}
lines.push('};', '');

const target = path.resolve(here, '../src/testing/role-permissions.ts');
fs.writeFileSync(target, lines.join('\n'));
console.log(`src/testing/role-permissions.ts written (${roles.length} roles)`);
